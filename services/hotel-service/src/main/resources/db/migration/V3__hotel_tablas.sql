-- Tablas del dominio hotel (hotel_db).
-- DDL de referencia: docs/especificacion/microservicios/hotel/base-de-datos.md#ddl-de-referencia
-- Las tablas tecnicas (api_idempotency, outbox, inbox) ya fueron creadas por V1/V2.

-- Catalogo fisico fijo: 1 LISTA, 2 EN_LIMPIEZA, 3 MANTENIMIENTO (se siembran en V4).
CREATE TABLE estado_habitacion (
  id          int PRIMARY KEY,
  codigo      varchar(30) NOT NULL UNIQUE,
  descripcion varchar(80) NOT NULL,
  estado      boolean     NOT NULL DEFAULT true,
  version     bigint      NOT NULL DEFAULT 1
);

CREATE TABLE hotel (
  id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug            varchar(80)  NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]+$'),
  nombre          varchar(120) NOT NULL,
  descripcion     varchar(300) NOT NULL,
  direccion       varchar(200) NOT NULL,
  ciudad          varchar(80)  NOT NULL,
  telefono        varchar(20)  NOT NULL,
  correo_contacto varchar(254) NOT NULL,
  estado          boolean      NOT NULL DEFAULT true,
  publicado       boolean      NOT NULL DEFAULT false,
  version         bigint       NOT NULL DEFAULT 1,
  created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE categoria (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(80)  NOT NULL UNIQUE,
  detalle     varchar(500) NOT NULL,
  capacidad   int          NOT NULL CHECK (capacidad BETWEEN 1 AND 10),
  estado      boolean      NOT NULL DEFAULT true,
  version     bigint       NOT NULL DEFAULT 1
);

CREATE TABLE piso (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hotel    int          NOT NULL REFERENCES hotel(id),
  descripcion varchar(80)  NOT NULL,
  estado      boolean      NOT NULL DEFAULT true,
  version     bigint       NOT NULL DEFAULT 1,
  UNIQUE (id_hotel, descripcion),
  UNIQUE (id, id_hotel)
);

CREATE TABLE habitacion (
  id                         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hotel                   int           NOT NULL,
  id_piso                    int           NOT NULL,
  id_categoria               int           NOT NULL REFERENCES categoria(id),
  numero                     varchar(10)   NOT NULL,
  detalle                    varchar(500)  NOT NULL,
  precio                     numeric(12,2) NOT NULL CHECK (precio > 0),
  id_estado_habitacion       int           NOT NULL REFERENCES estado_habitacion(id),
  estado                     boolean       NOT NULL DEFAULT true,
  publicada                  boolean       NOT NULL DEFAULT false,
  version                    bigint        NOT NULL DEFAULT 1,
  last_cleaning_room_version bigint        NOT NULL DEFAULT 0,
  FOREIGN KEY (id_piso, id_hotel) REFERENCES piso (id, id_hotel)
);
CREATE UNIQUE INDEX uq_habitacion_numero_activa ON habitacion (id_hotel, numero) WHERE estado;
CREATE INDEX ix_habitacion_sede_categoria ON habitacion (id_hotel, id_categoria, estado);

CREATE TABLE imagen_habitacion (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_habitacion int          NOT NULL REFERENCES habitacion(id),
  url           varchar(500) NOT NULL,
  alt           varchar(150) NOT NULL,
  orden         int          NOT NULL,
  UNIQUE (id_habitacion, orden)
);

CREATE TABLE ocupacion_projection (
  id_habitacion  int PRIMARY KEY,
  id_recepcion   int,
  estado_estadia varchar(16) NOT NULL,
  room_version   bigint      NOT NULL,
  updated_at     timestamptz NOT NULL DEFAULT now()
);

-- Catalogo publico de solo lectura: sedes publicadas/activas y categorias con
-- habitaciones publicadas/activas; precioDesde minimo publicado y galeria curada.
-- p_slug / p_categoria nulos => todos los publicados.
CREATE OR REPLACE FUNCTION fn_catalogo_publico(p_slug varchar, p_categoria int)
RETURNS TABLE (
  id_hotel     int,
  slug         varchar,
  nombre       varchar,
  id_categoria int,
  descripcion  varchar,
  capacidad    int,
  precio_desde numeric,
  imagenes     jsonb
) LANGUAGE sql STABLE AS $$
  SELECT
    h.id,
    h.slug,
    h.nombre,
    c.id,
    c.descripcion,
    c.capacidad,
    MIN(hab.precio) AS precio_desde,
    COALESCE(
      (SELECT jsonb_agg(jsonb_build_object('url', i.url, 'alt', i.alt) ORDER BY i.orden)
       FROM imagen_habitacion i
       JOIN habitacion h2 ON h2.id = i.id_habitacion
       WHERE h2.id_hotel = h.id AND h2.id_categoria = c.id
         AND h2.estado AND h2.publicada
       LIMIT 10),
      '[]'::jsonb) AS imagenes
  FROM hotel h
  JOIN categoria c ON true
  JOIN habitacion hab ON hab.id_hotel = h.id AND hab.id_categoria = c.id
    AND hab.estado AND hab.publicada AND hab.id_estado_habitacion = 1
  WHERE h.estado AND h.publicado
    AND (p_slug IS NULL OR h.slug = p_slug)
    AND (p_categoria IS NULL OR c.id = p_categoria)
  GROUP BY h.id, h.slug, h.nombre, c.id, c.descripcion, c.capacidad
$$;
