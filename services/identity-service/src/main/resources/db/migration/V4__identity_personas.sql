-- Esquema de negocio de identity: catálogo fijo de roles, personas, sedes autorizadas y
-- clientes de servicio.
-- DDL de referencia (fuente única): docs/especificacion/microservicios/identity/base-de-datos.md
-- §DDL de referencia. Las tablas técnicas (api_idempotency, outbox, inbox, audit_log) ya
-- venían de la convención común y no se duplican aquí.
--
-- Flyway corre con el usuario migrador; el runtime (identity_app) solo tiene DML por los
-- privilegios por defecto, así que no puede crear tablas ni alterarlas.

-- Catálogo fijo de roles: 1 ADMIN, 2 EMPLEADO, 3 CLIENTE. `codigo` es inmutable y es lo que
-- usa la autorización; `descripcion` es solo la etiqueta editable.
CREATE TABLE tipo_persona (
  id          int PRIMARY KEY,
  codigo      varchar(20) NOT NULL UNIQUE,
  descripcion varchar(80) NOT NULL,
  estado      boolean     NOT NULL DEFAULT true,
  version     bigint      NOT NULL DEFAULT 1
);

CREATE TABLE persona (
  id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento  varchar(12)  NOT NULL CHECK (tipo_documento IN ('DNI','PASAPORTE','CE')),
  documento       varchar(20)  NOT NULL,
  nombre          varchar(100) NOT NULL,
  apellido        varchar(100) NOT NULL,
  correo          varchar(254) NOT NULL UNIQUE,  -- normalizado a lowercase por el service
  clave_hash      varchar(255),
  foto_url        varchar(500),
  id_tipo_persona int          NOT NULL REFERENCES tipo_persona(id),
  estado          boolean      NOT NULL DEFAULT true,
  version         bigint       NOT NULL DEFAULT 1,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  UNIQUE (tipo_documento, documento),
  CHECK (tipo_documento <> 'DNI' OR documento ~ '^[0-9]{8}$'),
  CHECK (tipo_documento = 'DNI' OR documento ~ '^[A-Za-z0-9]{6,20}$')
);
CREATE INDEX ix_persona_documento ON persona (tipo_documento, documento);
CREATE INDEX ix_persona_correo ON persona (correo);

CREATE TABLE persona_sede (
  id_persona int NOT NULL REFERENCES persona(id),
  id_hotel   int NOT NULL,             -- id externo (hotel_db), validado por Feign
  PRIMARY KEY (id_persona, id_hotel)
);
CREATE INDEX ix_persona_sede_hotel ON persona_sede (id_hotel, id_persona);

-- Credenciales de servicio a servicio. No comparten credencial humana y no exponen el secreto.
CREATE TABLE service_client (
  client_id         varchar(80)  PRIMARY KEY,
  secret_hash       varchar(255) NOT NULL,
  audiencias_scopes jsonb        NOT NULL,   -- {"<audiencia>":["scope", ...]}
  estado            boolean      NOT NULL DEFAULT true
);

-- Los seeds de dev insertan personas con id explícito (1..4, 100 y 101), así que la identidad de
-- la tabla se deja por detrás del mayor id reservado: "secuencias se ajustan tras IDs explícitos"
-- (docs/especificacion/microservicios/identity/base-de-datos.md § Seeds).
-- Se ajusta aquí y no en el seeder porque el usuario runtime solo tiene USAGE/SELECT sobre las
-- secuencias (infra/postgres/init/01-bases-y-roles.sh): setval exige UPDATE y es del migrador.
SELECT setval(pg_get_serial_sequence('persona', 'id'), 101, true);