-- Esquema de dominio de reception_db (docs/especificacion/microservicios/reception/base-de-datos.md
-- § DDL de referencia). Las tablas técnicas V1/V2 son la convención de plataforma ya mergeada.
-- cierre y sus procedimientos pertenecen a back-reception-cierre (F4) y no se crean aquí.

CREATE TABLE recepcion (
  id                        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hotel                  int           NOT NULL,
  id_habitacion             int           NOT NULL,
  id_cliente                int           NOT NULL,
  cliente_snapshot          jsonb         NOT NULL,
  habitacion_snapshot       jsonb         NOT NULL,
  tarifa                    numeric(12,2) NOT NULL CHECK (tarifa > 0),
  fecha_entrada             date          NOT NULL,
  fecha_salida              date          NOT NULL,
  fecha_salida_confirmacion timestamptz,
  precio_inicial            numeric(12,2) NOT NULL CHECK (precio_inicial >= 0),
  adelanto                  numeric(12,2) NOT NULL CHECK (adelanto >= 0),
  medio_pago_adelanto       varchar(12)   CHECK (medio_pago_adelanto IN ('EFECTIVO','TARJETA','OTRO')),
  precio_restante           numeric(12,2) NOT NULL CHECK (precio_restante >= 0),
  total_pagado              numeric(12,2) NOT NULL CHECK (total_pagado >= 0),
  costo_penalidad           numeric(12,2) NOT NULL DEFAULT 0 CHECK (costo_penalidad >= 0),
  motivo_penalidad          varchar(300),
  estado_estadia            varchar(16)   NOT NULL CHECK (estado_estadia IN ('ACTIVA','CERRANDO','CERRADA')),
  observacion               varchar(500),
  archivada                 boolean       NOT NULL DEFAULT false,
  version                   bigint        NOT NULL DEFAULT 1,
  created_at                timestamptz   NOT NULL DEFAULT now(),
  CHECK (fecha_salida >= fecha_entrada),
  CHECK (adelanto <= precio_inicial),
  CHECK (costo_penalidad <= precio_inicial),
  CHECK (costo_penalidad = 0 OR motivo_penalidad IS NOT NULL)
);
CREATE UNIQUE INDEX uq_recepcion_habitacion_activa ON recepcion (id_habitacion)
  WHERE estado_estadia IN ('ACTIVA','CERRANDO');
CREATE INDEX ix_recepcion_hotel_estado ON recepcion (id_hotel, estado_estadia);
CREATE INDEX ix_recepcion_cliente ON recepcion (id_cliente, created_at);

CREATE TABLE room_gate (
  id_habitacion     int PRIMARY KEY,
  id_hotel          int         NOT NULL,
  estado            varchar(24) NOT NULL CHECK (estado IN ('LIBRE','OCUPADA','LIMPIEZA_PENDIENTE','BLOQUEADA')),
  id_recepcion      int REFERENCES recepcion(id),
  cleaning_cycle_id uuid,
  block_id          uuid,
  room_version      bigint      NOT NULL DEFAULT 0,
  hotel_version     bigint      NOT NULL,
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (estado <> 'OCUPADA' OR id_recepcion IS NOT NULL),
  CHECK (estado <> 'LIMPIEZA_PENDIENTE' OR cleaning_cycle_id IS NOT NULL),
  CHECK (estado <> 'BLOQUEADA' OR block_id IS NOT NULL)
);

CREATE TABLE operacion_consumo (
  operation_id uuid PRIMARY KEY,
  id_recepcion int         NOT NULL REFERENCES recepcion(id),
  id_venta     int         NOT NULL,
  tipo         varchar(12) NOT NULL CHECK (tipo IN ('VENTA','PAGO','ANULACION')),
  estado       varchar(12) NOT NULL CHECK (estado IN ('ABIERTA','FINALIZADA')),
  resultado    varchar(30),
  created_at   timestamptz NOT NULL DEFAULT now(),
  finished_at  timestamptz,
  UNIQUE (id_venta, operation_id),
  CHECK (estado <> 'FINALIZADA' OR resultado IS NOT NULL)
);
CREATE INDEX ix_operacion_recepcion_estado ON operacion_consumo (id_recepcion, estado);

CREATE TABLE bloqueo_habitacion (
  block_id      uuid         PRIMARY KEY,
  id_habitacion int          NOT NULL,
  id_hotel      int          NOT NULL,
  motivo        varchar(300) NOT NULL,
  request_hash  char(64)     NOT NULL,
  estado        varchar(12)  NOT NULL CHECK (estado IN ('ACTIVO','LIBERADO','RECHAZADO')),
  error_code    varchar(80),
  created_at    timestamptz  NOT NULL DEFAULT now(),
  released_at   timestamptz,
  CHECK (estado <> 'RECHAZADO' OR error_code IS NOT NULL)
);
CREATE INDEX ix_bloqueo_habitacion ON bloqueo_habitacion (id_habitacion, estado);

CREATE TABLE audit_log (
  id             uuid PRIMARY KEY,
  actor          varchar(100) NOT NULL,
  action         varchar(80)  NOT NULL,
  resource_id    varchar(80)  NOT NULL,
  id_hotel       int,
  correlation_id uuid         NOT NULL,
  occurred_at    timestamptz  NOT NULL DEFAULT now(),
  changes        jsonb
);
