-- Tablas de dominio de inventory (docs/especificacion/microservicios/inventory/base-de-datos.md #tablas).
-- V1 api_idempotency y V2 outbox/inbox ya las aportan los planes de plataforma.

CREATE TABLE producto (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku        varchar(40)  NOT NULL UNIQUE,
  nombre     varchar(120) NOT NULL,
  detalle    varchar(500),
  imagen_url varchar(500),
  estado     boolean      NOT NULL DEFAULT true,
  version    bigint       NOT NULL DEFAULT 1,
  created_at timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE producto_sede (
  id_producto int           NOT NULL REFERENCES producto(id),
  id_hotel    int           NOT NULL,          -- referencia externa (hotel_db), sin FK transversal
  precio      numeric(12,2) NOT NULL CHECK (precio > 0),
  cantidad    int           NOT NULL CHECK (cantidad >= 0),
  umbral_bajo int           NOT NULL CHECK (umbral_bajo >= 0),
  estado      boolean       NOT NULL DEFAULT true,
  version     bigint        NOT NULL DEFAULT 1,
  PRIMARY KEY (id_producto, id_hotel)
);
CREATE INDEX ix_producto_sede_hotel ON producto_sede (id_hotel, estado);

CREATE TABLE movimiento_venta (
  id_venta     int PRIMARY KEY,                -- id externo (sales_db)
  id_hotel     int         NOT NULL,
  request_hash char(64),
  estado       varchar(16) NOT NULL CHECK (estado IN ('DESCONTADO','RECHAZADO','RESTITUIDO')),
  resultado    jsonb,
  version      bigint      NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_movimiento_hotel ON movimiento_venta (id_hotel, created_at);

CREATE TABLE movimiento_detalle (
  id_venta        int           NOT NULL REFERENCES movimiento_venta(id_venta),
  id_producto     int           NOT NULL,
  cantidad        int           NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(12,2) NOT NULL CHECK (precio_unitario > 0),
  subtotal        numeric(12,2) NOT NULL CHECK (subtotal > 0),
  nombre_snapshot varchar(120)  NOT NULL,
  PRIMARY KEY (id_venta, id_producto)
);

CREATE TABLE ajuste_stock (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_producto      int          NOT NULL,
  id_hotel         int          NOT NULL,
  delta            int          NOT NULL CHECK (delta <> 0),
  motivo           varchar(300) NOT NULL,
  actor_id         int          NOT NULL,
  saldo_resultante int          NOT NULL CHECK (saldo_resultante >= 0),
  created_at       timestamptz  NOT NULL DEFAULT now(),
  FOREIGN KEY (id_producto, id_hotel) REFERENCES producto_sede (id_producto, id_hotel)
);

-- -----------------------------------------------------------------------
-- fn_stock_descontar: descuento atómico todo o nada de una venta.
-- Bloquea primero el movimiento por id_venta y luego las filas de stock
-- en orden ascendente de id_producto. Deduce con UPDATE condicional
-- cantidad >= solicitada y verifica filas afectadas; una línea
-- insuficiente revierte todo y registra RECHAZADO. Ítems duplicados se
-- rechazan antes de SQL (400 VALIDATION_ERROR desde el servicio).
-- Devuelve JSON con {estado, total, items[{idProducto,nombreProducto,cantidad,precioUnitario,subTotal}], version}.
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_stock_descontar(
  p_venta int,
  p_hotel int,
  p_items jsonb,
  p_hash char(64)
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(16);
  v_hash_existente char(64);
  v_resultado jsonb;
  v_version bigint;
  v_total numeric(12,2) := 0;
  v_item record;
  v_id_producto int;
  v_cantidad int;
  v_stock_actual int;
  v_estado_sede boolean;
  v_estado_producto boolean;
  v_precio numeric(12,2);
  v_nombre varchar(120);
  v_subtotal numeric(12,2);
  v_rows int;
BEGIN
  RAISE NOTICE 'DEBUG fn_stock_descontar: p_venta=%, p_hotel=%, p_hash=%', p_venta, p_hotel, p_hash;
  SELECT estado, request_hash, resultado, version INTO v_estado, v_hash_existente, v_resultado, v_version
  FROM movimiento_venta WHERE id_venta = p_venta FOR UPDATE;

  IF FOUND THEN
    IF 'RESTITUIDO' = v_estado THEN
      RETURN jsonb_build_object('estado', 'RECHAZADO', 'motivo', 'débito cancelado: la venta ya fue restituida', 'version', v_version);
    END IF;
    IF v_hash_existente IS NOT NULL AND v_hash_existente <> p_hash THEN
      RETURN jsonb_build_object('estado', 'IDEMPOTENCY_CONFLICT', 'motivo', 'mismo idVenta con hash distinto', 'version', v_version);
    END IF;
    RETURN v_resultado;
  END IF;

  INSERT INTO movimiento_venta (id_venta, id_hotel, request_hash, estado, resultado, version, created_at, updated_at)
  VALUES (p_venta, p_hotel, p_hash, 'RECHAZADO', NULL, 1, now(), now());
  RAISE NOTICE 'DEBUG after insert movimiento_venta';

  SELECT count(*) INTO v_rows FROM jsonb_array_elements(p_items);
  IF v_rows THEN
    UPDATE movimiento_venta SET estado = 'RECHAZADO', resultado = jsonb_build_object('estado','RECHAZADO','motivo','ítems de producto duplicados','version',1), updated_at = now() WHERE id_venta = p_venta;
    RETURN jsonb_build_object('estado','RECHAZADO','motivo','ítems de producto duplicados','version',1);
  END IF;
  RAISE NOTICE 'DEBUG after duplicate check';

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) ORDER BY (value->>'idProducto')::int
  LOOP
    RAISE NOTICE 'DEBUG loop: v_item.value=%', v_item.value;
    v_id_producto := (v_item.value->>'idProducto')::int;
    v_cantidad := (v_item.value->>'cantidad')::int;

    SELECT ps.cantidad, ps.estado, p.estado, ps.precio, p.nombre
    INTO v_stock_actual, v_estado_sede, v_estado_producto, v_precio, v_nombre
    FROM producto_sede ps
    JOIN producto p ON p.id = ps.id_producto
    WHERE ps.id_producto = v_id_producto AND ps.id_hotel = p_hotel
    FOR UPDATE;

    IF NOT FOUND THEN
      UPDATE movimiento_venta SET estado = 'RECHAZADO', resultado = jsonb_build_object('estado','RECHAZADO','motivo','producto no asignado a la sede','version',1), updated_at = now() WHERE id_venta = p_venta;
      RETURN jsonb_build_object('estado','RECHAZADO','motivo','producto no asignado a la sede','version',1);
    END IF;

    IF NOT v_estado_producto OR NOT v_estado_sede THEN
      UPDATE movimiento_venta SET estado = 'RECHAZADO', resultado = jsonb_build_object('estado','RECHAZADO','motivo','producto o sede inactivos','version',1), updated_at = now() WHERE id_venta = p_venta;
      RETURN jsonb_build_object('estado','RECHAZADO','motivo','producto o sede inactivos','version',1);
    END IF;

    IF v_stock_actual < v_cantidad THEN
      UPDATE movimiento_venta SET estado = 'RECHAZADO', resultado = jsonb_build_object('estado','RECHAZADO','motivo','stock insuficiente','version',1), updated_at = now() WHERE id_venta = p_venta;
      RETURN jsonb_build_object('estado','RECHAZADO','motivo','stock insuficiente','version',1);
    END IF;

    UPDATE producto_sede
    SET cantidad = cantidad - v_cantidad, version = version + 1, updated_at = now()
    WHERE id_producto = v_id_producto AND id_hotel = p_hotel AND cantidad >= v_cantidad;

    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows = 0 THEN
      UPDATE movimiento_venta SET estado = 'RECHAZADO', resultado = jsonb_build_object('estado','RECHAZADO','motivo','stock insuficiente (carrera)','version',1), updated_at = now() WHERE id_venta = p_venta;
      RETURN jsonb_build_object('estado','RECHAZADO','motivo','stock insuficiente (carrera)','version',1);
    END IF;

    v_subtotal := v_precio * v_cantidad;
    v_total := v_total + v_subtotal;

    INSERT INTO movimiento_detalle (id_venta, id_producto, cantidad, precio_unitario, subtotal, nombre_snapshot)
    VALUES (p_venta, v_id_producto, v_cantidad, v_precio, v_subtotal, v_nombre);
  END LOOP;

  v_resultado := jsonb_build_object(
    'estado', 'DESCONTADO',
    'total', round(v_total::numeric, 2),
    'moneda', 'PEN',
    'items', (
      SELECT jsonb_agg(jsonb_build_object(
        'idProducto', md.id_producto,
        'nombreProducto', md.nombre_snapshot,
        'cantidad', md.cantidad,
        'precioUnitario', md.precio_unitario,
        'subTotal', md.subtotal
      )) FROM movimiento_detalle md WHERE md.id_venta = p_venta
    ),
    'version', 1);

  UPDATE movimiento_venta
  SET estado = 'DESCONTADO', resultado = v_resultado, version = 1, updated_at = now()
  WHERE id_venta = p_venta;

  RETURN v_resultado;
END;
$$;

-- -----------------------------------------------------------------------
-- sp_stock_restituir: restitución idempotente con lápida.
-- Devuelve las cantidades originales una sola vez; si no hubo descuento
-- previo crea lápida RESTITUIDO sin detalles ni hash. Un débito tardío
-- sobre una lápida RESTITUIDO se rechaza con 409 DEBIT_CANCELLED.
-- -----------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_stock_restituir(
  p_venta int,
  p_hotel int,
  p_motivo varchar
)
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(16);
  v_resultado jsonb;
  v_version bigint;
  v_id_producto int;
  v_cantidad_devuelta int;
  v_rows int;
BEGIN
  -- Lock del mismo movimiento.
  SELECT estado, resultado, version INTO v_estado, v_resultado, v_version
  FROM movimiento_venta WHERE id_venta = p_venta FOR UPDATE;

  IF NOT FOUND THEN
    -- No hubo descuento: crear lápida RESTITUIDO que bloquea débitos tardíos.
    INSERT INTO movimiento_venta (id_venta, id_hotel, request_hash, estado, resultado, version, created_at, updated_at)
    VALUES (p_venta, p_hotel, NULL, 'RESTITUIDO',
      jsonb_build_object('estado','RESTITUIDO','motivo', p_motivo, 'restituidoAt', now(), 'version', 1),
      1, now(), now());
    RETURN;
  END IF;

  IF v_estado = 'RESTITUIDO' THEN
    -- Ya restituido: idempotente, no duplica stock.
    RETURN;
  END IF;

  IF v_estado = 'DESCONTADO' THEN
    -- Devuelve exactamente las cantidades originales una sola vez.
    FOR v_id_producto, v_cantidad_devuelta IN
      SELECT md.id_producto, md.cantidad FROM movimiento_detalle md WHERE md.id_venta = p_venta
    LOOP
      UPDATE producto_sede
      SET cantidad = cantidad + v_cantidad_devuelta, version = version + 1, updated_at = now()
      WHERE id_producto = v_id_producto AND id_hotel = p_hotel;

      GET DIAGNOSTICS v_rows = ROW_COUNT;
      IF v_rows = 0 THEN
        RAISE EXCEPTION 'producto_sede no encontrado para devolución id=% hotel=%', v_id_producto, p_hotel;
      END IF;
    END LOOP;

    -- Conserva el resultado DESCONTADO original para auditoría, añade restituidoAt.
    v_resultado := v_resultado || jsonb_build_object('restituidoAt', now());
    UPDATE movimiento_venta
    SET estado = 'RESTITUIDO', resultado = v_resultado, version = v_version + 1, updated_at = now()
    WHERE id_venta = p_venta;
  END IF;
  -- RECHAZADO: no hay stock que devolver; marca terminal sin cambios de cantidad.
END;
$$;

-- -----------------------------------------------------------------------
-- fn_stock_ajustar: ajuste manual de stock bajo lock; saldo nunca negativo.
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_stock_ajustar(
  p_id uuid,
  p_producto int,
  p_hotel int,
  p_delta int,
  p_motivo varchar,
  p_actor int
) RETURNS int
LANGUAGE plpgsql
AS $$
DECLARE
  v_saldo int;
  v_version bigint;
BEGIN
  SELECT ps.cantidad, ps.version INTO v_saldo, v_version
  FROM producto_sede ps
  WHERE ps.id_producto = p_producto AND ps.id_hotel = p_hotel
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'producto_sede no existe';
  END IF;

  IF v_saldo + p_delta < 0 THEN
    RAISE EXCEPTION 'ajuste dejaría saldo negativo';
  END IF;

  UPDATE producto_sede
  SET cantidad = v_saldo + p_delta, version = v_version + 1, updated_at = now()
  WHERE id_producto = p_producto AND id_hotel = p_hotel AND version = v_version;

  INSERT INTO ajuste_stock (id, id_producto, id_hotel, delta, motivo, actor_id, saldo_resultante, created_at)
  VALUES (p_id, p_producto, p_hotel, p_delta, p_motivo, p_actor, v_saldo + p_delta, now());

  RETURN v_saldo + p_delta;
END;
$$;

-- -----------------------------------------------------------------------
-- sp_producto_sede_crear: alta única de producto_sede con stock inicial.
-- -----------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_producto_sede_crear(
  p_producto int,
  p_hotel int,
  p_precio numeric,
  p_inicial int,
  p_umbral int
)
LANGUAGE plpgsql
AS $$
BEGIN
  INSERT INTO producto_sede (id_producto, id_hotel, precio, cantidad, umbral_bajo, estado, version)
  VALUES (p_producto, p_hotel, p_precio, p_inicial, p_umbral, true, 1)
  ON CONFLICT (id_producto, id_hotel) DO NOTHING;
END;
$$;

-- -----------------------------------------------------------------------
-- fn_productos_bajo_stock: consulta técnica local (reportes van a reporting).
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_productos_bajo_stock(p_hotel int, p_limite int)
RETURNS TABLE (id_producto int, cantidad int)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT ps.id_producto, ps.cantidad
  FROM producto_sede ps
  JOIN producto p ON p.id = ps.id_producto
  WHERE ps.id_hotel = p_hotel AND ps.estado AND p.estado AND ps.cantidad <= ps.umbral_bajo
  ORDER BY ps.id_producto
  LIMIT p_limite;
END;
$$;
